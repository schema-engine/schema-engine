import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/**
 * Locates `<monorepo>/registry/shared/forms/recipes` by walking up from the
 * current working directory.
 *
 * @remarks Neither `import.meta.url` nor `process.cwd()` is a stable anchor
 * here: ecopages bundles this module into `.eco/.server-collections/<section>/`
 * and executes it with a different working directory, so fixed relative paths
 * break. The registry lives outside the app, next to it in the monorepo — the
 * same convention as `additionalWatchPaths` in `eco.config.ts`.
 */
function findRecipesRoot(): string {
	let dir = process.cwd();
	for (let depth = 0; depth < 8; depth += 1) {
		const candidate = join(dir, 'registry/shared/forms/recipes');
		if (existsSync(candidate)) return candidate;
		const parent = dirname(dir);
		if (parent === dir) break;
		dir = parent;
	}
	throw new Error(`Unable to locate 'registry/shared/forms/recipes' from '${process.cwd()}'`);
}

const RECIPES_ROOT = findRecipesRoot();

/** Generated by scripts/generate-schema-engine-registry.ts alongside the recipe barrel. */
interface RecipeManifest {
	registry: string;
	recipes: Array<{ id: string; title: string; files: string[] }>;
}

export interface RecipeSourceFile {
	path: string;
	code: string;
}

export interface RecipeSourceGroup {
	id: string;
	title: string;
	files: RecipeSourceFile[];
}

function readRecipe(rel: string): RecipeSourceFile {
	return {
		path: `recipes/${rel}`,
		code: readFileSync(join(RECIPES_ROOT, rel), 'utf8'),
	};
}

const manifest = JSON.parse(readFileSync(join(RECIPES_ROOT, 'manifest.json'), 'utf8')) as RecipeManifest;

export const defaultRecipeSources: { registry: RecipeSourceFile; recipes: RecipeSourceGroup[] } = {
	registry: readRecipe(manifest.registry),
	recipes: manifest.recipes.map(({ id, title, files }) => ({
		id,
		title,
		files: files.map(readRecipe),
	})),
};
