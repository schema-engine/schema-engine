import { existsSync, globSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import autoprefixer from 'autoprefixer';
import postcss from 'postcss';
import nested from 'postcss-nested';
import tailwindcss from '@tailwindcss/postcss';
import { buildLib } from '@schema-engine/scripts/esbuild-lib';

const cwd = path.dirname(fileURLToPath(import.meta.url));
const outputDir = path.join(cwd, 'dist');

const entryDirs = ['src/components', 'src/contexts', 'src/hooks', 'src/types'];
const excludedCssFiles = ['styles.css'];

const postcssPlugin = {
	name: 'postcss',
	setup(build) {
		build.onLoad({ filter: /\.css$/ }, async (args) => {
			const source = readFileSync(args.path, 'utf8');
			const globalCss = path.join(cwd, 'src/styles/global.css');
			const isGlobal = path.resolve(args.path) === path.resolve(globalCss);
			const css = isGlobal ? source : `@reference "${globalCss}";\n${source}`;
			const result = await postcss([nested, tailwindcss, autoprefixer]).process(css, { from: args.path });
			return { contents: result.css, loader: 'css' };
		});
	},
};

function generateGlobalCSS() {
	const cssFiles = globSync('src/**/*.css', { cwd })
		.filter((file) => {
			if (excludedCssFiles.some((excluded) => file.endsWith(excluded))) {
				return false;
			}
			return entryDirs.some((dir) => file.startsWith(dir));
		})
		.toSorted();

	const lines = [
		'/* @schema-engine/forms-react styles */',
		'/* AUTO-GENERATED FILE - DO NOT EDIT MANUALLY */',
		'/* This file is automatically generated during build */',
		'/* To modify styles, edit the individual CSS files in src/components/ */',
		'',
		'/* This file imports all component styles */',
	];

	if (cssFiles.length > 0) {
		lines.push('');
	}

	for (const cssFile of cssFiles) {
		lines.push(`@import "${cssFile.replace('src/', './')}";`);
	}

	if (!existsSync(outputDir)) {
		mkdirSync(outputDir, { recursive: true });
	}

	writeFileSync(path.join(outputDir, 'global.css'), lines.join('\n'), 'utf8');
}

if (existsSync(outputDir) && !process.argv.includes('--watch')) {
	rmSync(outputDir, { recursive: true, force: true });
}

await buildLib({
	cwd,
	entryGlobs: [
		'src/index.ts',
		'src/*.ts',
		'src/*.tsx',
		'src/*.css',
		...entryDirs.flatMap((dir) => [`${dir}/**/*.ts`, `${dir}/**/*.tsx`, `${dir}/**/*.css`]),
	],
	exclude: ['.stories.', '.play.', '.test.'],
	plugins: [postcssPlugin],
	onEnd: generateGlobalCSS,
});
