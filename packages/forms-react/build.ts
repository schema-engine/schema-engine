import { type BunPlugin } from 'bun';
import { watch, rmSync, mkdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PostCssProcessor } from '@ecopages/postcss-processor';
import { Logger } from '@ecopages/logger';

const logger = new Logger('[@schema-engine/forms-react]');

const watchMode = process.argv.includes('--watch');
const outputDir = 'dist';
const sourceDir = 'src';

const SOURCE_FILE_EXTENSIONS = ['ts', 'tsx', 'css'];
const EXCLUDED_CSS_FILES = ['styles.css'];
const EXCLUDED_INCLUDES = ['.stories'];

function getFileAsBuffer(filePath: string): Buffer {
	try {
		if (!existsSync(filePath)) {
			throw new Error(`File: ${filePath} not found`);
		}
		return readFileSync(filePath);
	} catch (error) {
		const errorMessage = error instanceof Error ? error.message : String(error);
		throw new Error(`Error reading file: ${filePath}, ${errorMessage}`, { cause: error });
	}
}

const postcssPlugin: BunPlugin = {
	name: 'bun-postcss-loader',
	setup(build) {
		build.onLoad(
			{
				filter: /\.css$/,
				namespace: 'file',
			},
			async (args) => {
				try {
					const text = getFileAsBuffer(args.path);
					const contents = await PostCssProcessor.processStringOrBuffer(text);
					return {
						contents: contents,
						loader: 'css',
					};
				} catch (error) {
					const errorMessage = error instanceof Error ? error.message : String(error);
					logger.error(`Error processing CSS file ${args.path}: ${errorMessage}`);
					throw error;
				}
			},
		);
	},
};

const entryDirs = ['src/adapters', 'src/components', 'src/hooks', 'src/registries', 'src/types'];

async function discoverSourceFiles(): Promise<string[]> {
	const indexFiles = ['src/index.ts'];
	const extensionPattern = `{${SOURCE_FILE_EXTENSIONS.join(',')}}`;

	const directoryFiles = await Promise.all(
		entryDirs.map(async (dir) => {
			const glob = new Bun.Glob(`${dir}/**/*.${extensionPattern}`);
			return Array.fromAsync(glob.scan({ cwd: '.' }));
		}),
	).then((files) => files.flat());

	const rootSrcGlob = new Bun.Glob(`src/*.${extensionPattern}`);
	const rootSrcFiles = await Array.fromAsync(rootSrcGlob.scan({ cwd: '.' }));

	const allFiles = [...new Set([...indexFiles, ...directoryFiles, ...rootSrcFiles])];
	return allFiles.filter((file) => !EXCLUDED_INCLUDES.some((excluded) => file.includes(excluded)));
}

function ensureDirectoryExists(dirPath: string, forceCleanup = false): void {
	if (forceCleanup && existsSync(dirPath)) {
		rmSync(dirPath, { recursive: true, force: true });
	}
	mkdirSync(dirPath, { recursive: true });
}

async function generateGlobalCSS(): Promise<void> {
	const cssGlob = new Bun.Glob('src/**/*.css');
	const cssFiles = await Array.fromAsync(cssGlob.scan({ cwd: '.' }));

	const imports: string[] = [
		'/* JSON Form Engine React - Global Styles */',
		'/* AUTO-GENERATED FILE - DO NOT EDIT MANUALLY */',
		'/* This file is automatically generated during build */',
		'/* To modify styles, edit the individual CSS files in src/components/ */',
		'',
		'/* This file imports all component styles */',
	];

	const sortedFiles = cssFiles
		.filter((file) => {
			const isExcluded = EXCLUDED_CSS_FILES.some((excluded) => file.endsWith(excluded));
			const isInEntryDir = entryDirs.some((dir) => file.startsWith(dir));
			return !isExcluded && isInEntryDir;
		})
		.toSorted();

	if (sortedFiles.length > 0) {
		imports.push('');
	}

	for (const cssFile of sortedFiles) {
		const relativePath = cssFile.replace('src/', './');
		imports.push(`@import "${relativePath}";`);
	}

	const globalCSSContent = imports.join('\n');
	const globalCSSPath = path.join(outputDir, 'global.css');

	writeFileSync(globalCSSPath, globalCSSContent, 'utf-8');
}

async function build(): Promise<void> {
	const startTime = performance.now();

	try {
		ensureDirectoryExists(outputDir, true);

		const sourceFiles = await discoverSourceFiles();

		const buildResult = await Bun.build({
			entrypoints: sourceFiles,
			outdir: outputDir,
			root: './src',
			target: 'browser',
			minify: !watchMode,
			format: 'esm',
			splitting: !watchMode,
			sourcemap: 'external',
			external: ['react', 'react-dom', '@schema-engine/forms'],
			plugins: [postcssPlugin],
			define: {
				'process.env.NODE_ENV': watchMode ? '"development"' : '"production"',
			},
		});

		if (!buildResult.success) {
			console.error('Build failed:');
			for (const log of buildResult.logs) {
				console.error(log);
			}
			throw new Error('Build failed');
		}

		await generateGlobalCSS();

		const duration = Math.round(performance.now() - startTime);
		logger.info(`✓ Build completed successfully in ${duration}ms`);
	} catch (error) {
		const errorMessage = error instanceof Error ? error.message : String(error);
		logger.error(`Build failed: ${errorMessage}`);
		process.exit(1);
	}
}

function startWatch(): void {
	logger.info('Starting watch mode...');

	const watcher = watch(path.resolve(process.cwd(), sourceDir), { recursive: true }, async (eventType, filename) => {
		logger.info(`File ${eventType}: ${filename}`);
		try {
			await build();
		} catch (error) {
			const errorMessage = error instanceof Error ? error.message : String(error);
			logger.error(`Watch build failed: ${errorMessage}`);
		}
	});

	process.on('SIGINT', () => {
		console.log('Closing watcher...');
		watcher?.close();
		process.exit(0);
	});

	logger.info('Watching for changes...');
}

async function main() {
	await build();

	if (watchMode) {
		startWatch();
	}
}

main().catch((error) => {
	const errorMessage = error instanceof Error ? error.message : String(error);
	logger.error(`Fatal error: ${errorMessage}`);
	process.exit(1);
});
